export function airlineFromCallsign(callsign: string | null): string | null {
  if (!callsign) return null;
  const m = /^([A-Z]{3})\d/.exec(callsign.toUpperCase());
  return m ? (TABLE[m[1]!] ?? null) : null;
}

// the three letter prefix when the callsign has the airline-and-number shape
export function callsignPrefix(callsign: string | null): string | null {
  if (!callsign) return null;
  const m = /^([A-Z]{3})\d/.exec(callsign.toUpperCase());
  return m ? m[1]! : null;
}

// ICAO type codes of helicopters that commonly show up. the emitter category A7 is the main signal
const HELI = new Set(
  (
    'R22 R44 R66 B06 B06T B407 B412 B429 B430 B505 EC20 EC30 EC35 EC45 EC55 EC75 H125 H130 H135 H145 H155 H160 H175 H225 ' +
    'AS32 AS35 AS50 AS55 AS65 A109 A119 A139 A169 A189 S76 S92 S61 S64 S70 H60 H47 H53 H64 UH1 H500 H269 EN28 EN48 ' +
    'MD52 MD60 MDHI EXPL AS3B SA33 SA34 KMAX K226 BK17 MI8 MI17 MI24 KA32 R44 AW09 AW12'
  ).split(' '),
);

export function isHeliType(type: string | null): boolean {
  return !!type && HELI.has(type.toUpperCase());
}
